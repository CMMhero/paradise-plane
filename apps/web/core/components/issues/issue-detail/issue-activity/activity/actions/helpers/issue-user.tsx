// components
import { MemberProfileTrigger } from "@/components/member-profile";
// hooks
import { useIssueDetail } from "@/hooks/store/use-issue-detail";

type TIssueUser = {
  activityId: string;
  customUserName?: string;
};

export function IssueUser(props: TIssueUser) {
  const { activityId, customUserName } = props;
  // hooks
  const {
    activity: { getActivityById },
  } = useIssueDetail();

  const activity = getActivityById(activityId);

  if (!activity) return <></>;

  return (
    <>
      {customUserName ? (
        <span className="font-medium text-primary">{customUserName}</span>
      ) : (
        <MemberProfileTrigger userId={activity.actor_detail?.id}>
          <span className="font-medium text-primary hover:underline">{activity.actor_detail?.display_name}</span>
        </MemberProfileTrigger>
      )}
    </>
  );
}
