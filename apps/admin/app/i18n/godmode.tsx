export type TGodmodeStrings = typeof en;

/** For code outside React (route `meta`). Components use `useGodmodeStrings`. */
export const godmodeStrings: TGodmodeStrings = en;

const fill = (template: string, vars: Record<string, string | number>): string =>
  template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? `{${key}}`));

/** God Mode strings. `fill` swaps `{name}` placeholders, standing in for ICU which admin lacks. */
export function useGodmodeStrings(): {
  s: TGodmodeStrings;
  fill: (template: string, vars: Record<string, string | number>) => string;
} {
  return { s: en, fill };
}
